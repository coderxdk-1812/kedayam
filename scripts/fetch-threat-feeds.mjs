#!/usr/bin/env node
// Kedayam — build-time threat-feed snapshot generator.
//
// Pulls the FREE, key-less public blocklists (URLhaus, Phishing Army, OpenPhish)
// and bakes a deduplicated, bounded snapshot into the signed bundle as
// `extension/lib/rules/blocklistSnapshot.js`. This gives DAY-ONE offline
// coverage of thousands of known-bad hosts with zero network calls at runtime —
// the small hand seed in blocklistSeed.js was only ever a placeholder.
//
// This is a DELIBERATE, committed generation step (like the icons), NOT part of
// the per-build pipeline: feed contents change over time, so baking them on
// every build would make the release non-reproducible. Run it when you cut a
// release:  `bun run feeds:snapshot`  then commit the updated snapshot.
//
// Privacy note: this script only downloads the public feed files. Nothing about
// any user's browsing is involved — it runs on the developer's machine at build.

import { writeFileSync } from "node:fs";
import { FREE_FEEDS, parseFeed } from "../extension/lib/threatFeed.js";
import { BLOCKLIST_SEED } from "../extension/lib/rules/blocklistSeed.js";
import { rootDomain } from "../extension/lib/lookalike.js";
import { isSafelistedRoot } from "../extension/lib/safelist.js";
import { KNOWN_REPUTABLE_ROOTS, TRUSTED_LOGIN_PROVIDERS } from "../extension/lib/trustEngine.js";

// Public feeds occasionally list a legitimate root (e.g. github.com, where a
// user page once hosted a phishing kit). NEVER bake a known-good root into the
// bundled blocklist — that would be a shipped false positive. Filter every
// candidate host against the same trust sets the engine uses.
function isNeverBlock(host) {
  const root = rootDomain(host);
  return (
    KNOWN_REPUTABLE_ROOTS.has(host) ||
    KNOWN_REPUTABLE_ROOTS.has(root) ||
    TRUSTED_LOGIN_PROVIDERS.has(host) ||
    TRUSTED_LOGIN_PROVIDERS.has(root) ||
    isSafelistedRoot(host) ||
    isSafelistedRoot(root)
  );
}

// Keep the bundled snapshot bounded so the zip stays small and load stays fast.
// The opt-in runtime refresh (threatFeed.js) layers the full lists on top later.
const MAX_SNAPSHOT = Number(process.env.KEDAYAM_SNAPSHOT_MAX || 12000);
const OUT = "extension/lib/rules/blocklistSnapshot.js";

async function pull(feed) {
  try {
    const res = await fetch(feed.url, {
      headers: { "user-agent": "kedayam-shield-build/1.0" },
      redirect: "follow",
    });
    if (!res.ok) {
      console.warn(`[feeds] ${feed.id}: HTTP ${res.status} — skipped`);
      return new Set();
    }
    const text = await res.text();
    const set = parseFeed(text);
    console.log(`[feeds] ${feed.id}: ${set.size} hosts`);
    return set;
  } catch (e) {
    console.warn(`[feeds] ${feed.id}: ${e.message} — skipped`);
    return new Set();
  }
}

const seed = new Set(BLOCKLIST_SEED);
const merged = new Set();
const sources = [];
for (const feed of FREE_FEEDS) {
  const set = await pull(feed);
  if (set.size) sources.push({ id: feed.id, count: set.size });
  for (const h of set) {
    if (seed.has(h)) continue; // seed already covers it
    if (isNeverBlock(h)) continue; // never ship a known-good root as blocked
    merged.add(h);
    if (merged.size >= MAX_SNAPSHOT) break;
  }
  if (merged.size >= MAX_SNAPSHOT) break;
}

if (merged.size === 0) {
  console.error(
    "[feeds] no hosts fetched (offline?) — refusing to overwrite the snapshot with an empty list.",
  );
  process.exit(1);
}

// Sorted → the generated file has a stable, diff-friendly order for a given
// feed state, so re-running only shows genuine additions/removals.
const hosts = Array.from(merged).sort();
const body = `// Kedayam — bundled threat-blocklist snapshot (AUTO-GENERATED).
//
// Generated by \`bun run feeds:snapshot\` from the FREE public feeds
// (${sources.map((s) => s.id).join(", ") || "none"}). DO NOT edit by hand — re-run
// the generator and commit. ${hosts.length} deduplicated hosts (cap ${MAX_SNAPSHOT}).
// This ships offline in the signed bundle; the opt-in runtime refresh layers the
// full lists on top. Matching is host + eTLD+1, same as the seed.
export const BLOCKLIST_SNAPSHOT = Object.freeze([
${hosts.map((h) => `  ${JSON.stringify(h)},`).join("\n")}
]);
`;

writeFileSync(OUT, body);
console.log(
  `[feeds] wrote ${OUT} — ${hosts.length} hosts from ${sources.length} feed(s) (${sources
    .map((s) => `${s.id}:${s.count}`)
    .join(", ")}).`,
);
